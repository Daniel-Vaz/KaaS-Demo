// Status reports the registry's health, cached briefly so the Registry page does not put a
// round-trip on every load. A failure is a REPORT, not an error: the page renders "unreachable"
// rather than a 500, the same way the health panel treats an unreachable cluster.
func (c *Client) Status(ctx context.Context) registry.Status {
	c.mu.Lock()
	if time.Since(c.statusAt) < statusTTL && c.status.Configured {
		st := c.status
		c.mu.Unlock()
		return st
	}
	c.mu.Unlock()

	st := registry.Status{
		Configured:     true,
		Host:           c.set.Host,
		UIURL:          c.set.UIURL,
		AuthMode:       c.set.AuthMode,
		Mirror:         c.set.Mirror,
		CanSetPassword: c.set.CanSetPasswords(),
	}
	for _, u := range c.set.Upstreams {
		st.Upstreams = append(st.Upstreams, u.Host)
	}
	var health struct {
		Status string `json:"status"`
	}
	if err := c.do(ctx, http.MethodGet, "/health", nil, &health); err != nil {
		st.Message = err.Error()
	} else {
		st.Healthy = strings.EqualFold(health.Status, "healthy")
		if !st.Healthy {
			st.Message = "registry reports " + health.Status
		}
	}
	var info struct {
		Version string `json:"harbor_version"`
	}
	if err := c.do(ctx, http.MethodGet, "/systeminfo", nil, &info); err == nil {
		st.Version = info.Version
	}
	// The mode Harbor is really in, which is not necessarily the one this deployment intends - see
	// registry.Status.AuthMode. Best-effort: /configurations is admin-only, and the production shape
	// for the API's credential is a read-only robot, so a failure here keeps the configured value.
	if mode, err := c.readAuthMode(ctx); err == nil && mode != "" {
		st.AuthMode = mode
		// And the button follows the REAL mode: offering "generate a password" against a directory
		// account cannot work, and hiding it on a Harbor that is actually on its own user database
		// would withhold the only way to get a password out of the platform.
		st.CanSetPassword = mode == registry.AuthLocal && !strings.HasPrefix(c.set.Username, "robot$")
	}

	c.mu.Lock()
	c.status, c.statusAt = st, time.Now()
	c.mu.Unlock()
	return st
}

// readAuthMode reports which identity source the registry is actually using, translated into the
// platform's own vocabulary so the portal renders one set of names. Harbor's modes that the platform
// has no word for (uaa, oidc, http) are returned verbatim rather than forced into local/ldap: an
// operator running Harbor behind an IdP should see that, not be told "local accounts".
func (c *Client) readAuthMode(ctx context.Context) (string, error) {
	var cfg struct {
		AuthMode struct {
			Value string `json:"value"`
		} `json:"auth_mode"`
	}
	if err := c.do(ctx, http.MethodGet, "/configurations", nil, &cfg); err != nil {
		return "", err
	}
	switch v := strings.TrimSpace(cfg.AuthMode.Value); v {
	case "":
		return "", nil
	case "db_auth":
		return registry.AuthLocal, nil
	case "ldap_auth":
		return registry.AuthLDAP, nil
	default:
		return v, nil
	}
}

func (c *Client) Projects(ctx context.Context) ([]registry.Project, error) {
	var list []struct {
		Name       string            `json:"name"`
		RepoCount  int               `json:"repo_count"`
		RegistryID int64             `json:"registry_id"`
		UpdateTime time.Time         `json:"update_time"`
		Metadata   map[string]string `json:"metadata"`
	}
	if err := c.do(ctx, http.MethodGet, "/projects?page_size=100&with_detail=true", nil, &list); err != nil {
		return nil, err
	}
	out := make([]registry.Project, 0, len(list))
	for _, p := range list {
		out = append(out, registry.Project{
			Name:      p.Name,
			Kind:      c.kindOf(p.Name, p.RegistryID != 0),
			Public:    p.Metadata["public"] == "true",
			RepoCount: p.RepoCount,
			UpdatedAt: p.UpdateTime,
			Upstream:  c.upstreamOf(p.Name),
		})
	}
	return out, nil
}

// kindOf classifies a project. Anything the platform did not name is external - shown to admins
// only, and never touched by SyncAccess.
func (c *Client) kindOf(name string, proxied bool) registry.ProjectKind {
	switch {
	case name == c.set.Library():
		return registry.KindLibrary
	case proxied || strings.HasPrefix(name, c.set.ProjectPrefix+"cache-"):
		return registry.KindCache
	case strings.HasPrefix(name, c.set.ProjectPrefix):
		return registry.KindCluster
	}
	return registry.KindExternal
}

func (c *Client) upstreamOf(project string) string {
	for _, u := range c.set.Upstreams {
		if c.set.CacheProject(u) == project {
			return u.Host
		}
	}
	return ""
}

func (c *Client) Repositories(ctx context.Context, project string) ([]registry.Repository, error) {
	return c.repositories(ctx, project)
}

func (c *Client) repositories(ctx context.Context, project string) ([]registry.Repository, error) {
	var list []struct {
		Name          string    `json:"name"`
		ArtifactCount int       `json:"artifact_count"`
		PullCount     int64     `json:"pull_count"`
		UpdateTime    time.Time `json:"update_time"`
	}
	if err := c.do(ctx, http.MethodGet,
		"/projects/"+url.PathEscape(project)+"/repositories?page_size=100", nil, &list,
		http.StatusNotFound); err != nil {
		return nil, err
	}
	out := make([]registry.Repository, 0, len(list))
	for _, r := range list {
		out = append(out, registry.Repository{
			// Harbor returns the fully-qualified "<project>/<name>"; the portal wants the short one.
			Name:          strings.TrimPrefix(r.Name, project+"/"),
			FullName:      r.Name,
			ArtifactCount: r.ArtifactCount,
			PullCount:     r.PullCount,
			UpdatedAt:     r.UpdateTime,
		})
	}
	return out, nil
}

func (c *Client) Artifacts(ctx context.Context, project, repo string) ([]registry.Artifact, error) {
	var list []struct {
		Digest   string    `json:"digest"`
		Size     int64     `json:"size"`
		PushTime time.Time `json:"push_time"`
		Type     string    `json:"type"`
		Tags     []struct {
			Name string `json:"name"`
		} `json:"tags"`
	}
	// The scan overview is deliberately NOT requested (`with_scan_overview`): the Security page reads
	// the trivy-operator inside each cluster, and the registry does not publish a second summary.
	path := "/projects/" + url.PathEscape(project) + "/repositories/" + repoPath(repo) +
		"/artifacts?page_size=100&with_tag=true"
	if err := c.do(ctx, http.MethodGet, path, nil, &list, http.StatusNotFound); err != nil {
		return nil, err
	}
	out := make([]registry.Artifact, 0, len(list))
	for _, a := range list {
		art := registry.Artifact{
			Digest:    a.Digest,
			SizeBytes: a.Size,
			PushedAt:  a.PushTime,
			Type:      a.Type,
		}
		for _, t := range a.Tags {
			art.Tags = append(art.Tags, t.Name)
		}
		out = append(out, art)
	}
	return out, nil
}

// repoPath escapes a repository name for a Harbor path segment. Harbor nests repositories with
// slashes ("cilium/cilium") but takes them as ONE path segment, so the slash must be double-escaped
// - a single url.PathEscape leaves "%2F", which Harbor's router splits on anyway.
func repoPath(repo string) string {
	return strings.ReplaceAll(url.PathEscape(repo), "%2F", "%252F")
}

// roleID maps the platform's role vocabulary onto Harbor's numeric project roles.
func roleID(r registry.Role) int {
	switch r {
	case registry.RoleProjectAdmin:
		return 1
	case registry.RoleDeveloper:
		return 2
	case registry.RoleGuest:
		return 3
	}
	return 3
}

// randomPassword generates a throwaway that satisfies Harbor's complexity rule (8+ characters with
// upper, lower and a digit). Used for a local account at creation, before its owner sets their own.
func randomPassword() string {
	return registry.GeneratePassword()
}
