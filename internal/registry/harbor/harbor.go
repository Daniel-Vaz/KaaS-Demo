// EnsurePlatform provisions everything that is not per-cluster: the auth backend mirroring the
// portal, the library project, one proxy-cache project (and its upstream registry endpoint) per
// mirrored host, and the garbage-collection schedule that stops the cache growing without bound.
//
// It mints NO credential. The cache and library projects are PUBLIC, so a cluster node pulls
// through them anonymously and no fleet-wide secret ever lands on a tenant's VM - see
// registry.NodeTrust for why that is the right trade and what it costs. Idempotent throughout: a 409
// "already exists" is success.
func (c *Client) EnsurePlatform(ctx context.Context) error {
	// Auth is NOT configured here - see registry.Manager.EnsureAuth. This runs on the worker, which
	// has no directory settings, so it would only ever no-op.
	//
	// Public: a node pulls the platform's own images with no credential at all.
	if err := c.ensureProject(ctx, c.set.Library(), true, 0, ""); err != nil {
		return err
	}
	if c.set.Mirror {
		// Per-upstream failures are logged and STEPPED OVER rather than returned. Each cache is an
		// independent optimisation for one upstream, and every hosts.toml keeps the upstream as its
		// `server` fallback - so a cache that cannot be created costs pull speed for that one
		// registry. Returning here instead made a single unsupported provider type abort the whole
		// platform bootstrap: the caches after it, the GC schedule, and - because the reconciler
		// retries the same failing call forever - every per-cluster project too. One upstream Harbor
		// dislikes must not cost the tenant registry.
		for _, u := range c.set.Upstreams {
			id, err := c.ensureUpstream(ctx, u)
			if err != nil {
				c.emit("", "warn", fmt.Sprintf("registry: could not register the %s upstream, so it will not be cached (nodes still pull it directly): %v", u.Name, err))
				continue
			}
			// Public, for the reason above: the contents are public upstream images, and making a
			// node authenticate to reach them would buy nothing and cost a fleet credential.
			if err := c.ensureProject(ctx, c.set.CacheProject(u), true, 0, strconv.FormatInt(id, 10)); err != nil {
				c.emit("", "warn", fmt.Sprintf("registry: could not create the %s cache project (nodes still pull it directly): %v", u.Name, err))
			}
		}
	}
	if err := c.ensureGCSchedule(ctx); err != nil {
		// Not fatal: the registry works, it just needs manual housekeeping. Say so rather than
		// failing platform setup over a cleanup schedule.
		c.emit("", "warn", "registry: could not set the garbage-collection schedule: "+err.Error())
	}
	c.emit("", "info", fmt.Sprintf("registry: provisioned the platform projects at %s (mirror=%v)", c.set.Host, c.set.Mirror))
	return nil
}

// EnsureAuth points Harbor at the same identity source the portal uses. In ldap mode it writes the
// same directory settings the portal and Vault read from the mounted ldap.yaml, so a user's one set
// of credentials works in all three. Self-registration is turned off in both modes: the platform is
// the only way an account comes into existence.
func (c *Client) EnsureAuth(ctx context.Context) error {
	if !c.set.ManageAuth {
		// This process cannot see the directory configuration, so it has no authoritative view of how
		// the registry should authenticate - see registry.Settings.ManageAuth. Writing the fallback
		// would lock every user out.
		c.emit("", "info", "registry: leaving the registry's authentication configuration untouched (no directory config in this process)")
		return nil
	}
	cfg := map[string]any{
		"self_registration":            false,
		"project_creation_restriction": "adminonly",
	}
	switch c.set.AuthMode {
	case registry.AuthLDAP:
		l := c.set.LDAP
		cfg["auth_mode"] = "ldap_auth"
		cfg["ldap_url"] = l.URL
		cfg["ldap_search_dn"] = l.BindDN
		cfg["ldap_search_password"] = l.BindPassword
		cfg["ldap_base_dn"] = l.BaseDN
		cfg["ldap_uid"] = l.UID
		cfg["ldap_verify_cert"] = l.VerifyCert
		cfg["ldap_scope"] = 2 // subtree
	default:
		cfg["auth_mode"] = "db_auth"
	}
	err := c.do(ctx, http.MethodPut, "/configurations", cfg, nil)
	if err == nil {
		c.emit("", "info", "registry: configured the registry's authentication ("+c.set.AuthMode+")")
		return nil
	}
	// Harbor refuses to change auth_mode once its own database holds any user, because switching
	// would orphan them - so this is not a transient failure and retrying never clears it. It is
	// worth naming precisely, since the state that causes it is usually invisible: a single local
	// account created before the mode was set is enough, and the remedy is to delete those accounts
	// (the platform's own are recreated) rather than anything about this configuration.
	if strings.Contains(err.Error(), "auth mode cannot be modified") {
		return fmt.Errorf("%w - the registry already holds local accounts, and it will not change auth mode while any exist; delete them in the registry's Administration > Users and this will apply on the next start-up", err)
	}
	return err
}

// ensureUpstream registers (or updates) the remote registry a proxy-cache project pulls through, and
// returns its id. Docker Hub credentials matter here: an anonymous proxy inherits Docker Hub's
// anonymous rate limit for the WHOLE fleet, which is one of the failures this integration exists to
// remove.
func (c *Client) ensureUpstream(ctx context.Context, u registry.Upstream) (int64, error) {
	name := "kaas-" + u.Name
	body := map[string]any{
		"name":        name,
		"type":        u.Type,
		"url":         u.Endpoint,
		"insecure":    false,
		"description": "Managed by KubeHarbor - proxy cache upstream for " + u.Host,
	}
	if cred, ok := c.set.UpstreamAuth[u.Name]; ok && cred.Username != "" {
		body["credential"] = map[string]any{
			"type":          "basic",
			"access_key":    cred.Username,
			"access_secret": cred.Password,
		}
	}
	if err := c.do(ctx, http.MethodPost, "/registries", body, nil, http.StatusConflict); err != nil {
		return 0, err
	}
	var list []struct {
		ID   int64  `json:"id"`
		Name string `json:"name"`
	}
	if err := c.do(ctx, http.MethodGet, "/registries?q=name%3D"+url.QueryEscape(name)+"&page_size=100", nil, &list); err != nil {
		return 0, err
	}
	for _, r := range list {
		if r.Name == name {
			return r.ID, nil
		}
	}
	return 0, fmt.Errorf("harbor: upstream registry %q was neither created nor found", name)
}

// ensureProject creates a project if absent. registryID non-empty makes it a pull-through proxy of
// that upstream. Idempotent by way of the 409.
func (c *Client) ensureProject(ctx context.Context, name string, public bool, quotaGB int, registryID string) error {
	meta := map[string]string{"public": strconv.FormatBool(public)}
	if registryID == "" {
		// Scan on push and block the worst findings from being pulled. Only meaningful on a project
		// that receives pushes - a proxy cache mirrors whatever upstream holds.
		meta["auto_scan"] = "true"
	}
	body := map[string]any{"project_name": name, "metadata": meta}
	if registryID != "" {
		id, err := strconv.ParseInt(registryID, 10, 64)
		if err != nil {
			return err
		}
		body["registry_id"] = id
	}
	if quotaGB > 0 {
		body["storage_limit"] = int64(quotaGB) * 1024 * 1024 * 1024
	}
	return c.do(ctx, http.MethodPost, "/projects", body, nil, http.StatusConflict)
}

// ensureGCSchedule keeps the proxy cache from growing without bound. The registry lives on the same
// host whose capacity the platform's own quota is guarding, so untended cache growth is not a
// cosmetic problem: it competes with the VMs.
func (c *Client) ensureGCSchedule(ctx context.Context) error {
	body := map[string]any{
		"schedule":   map[string]any{"type": "Weekly", "cron": "0 0 3 * * 0"},
		"parameters": map[string]any{"delete_untagged": true},
	}
	// PUT replaces an existing schedule; POST creates the first one. Try the update, fall back.
	if err := c.do(ctx, http.MethodPut, "/system/gc/schedule", body, nil); err == nil {
		return nil
	}
	return c.do(ctx, http.MethodPost, "/system/gc/schedule", body, nil, http.StatusConflict)
}

// findRobot resolves a robot's id and full name (Harbor prefixes "robot$") from the short name.
func (c *Client) findRobot(ctx context.Context, short string) (int64, string, error) {
	var list []struct {
		ID   int64  `json:"id"`
		Name string `json:"name"`
	}
	if err := c.do(ctx, http.MethodGet, "/robots?page_size=100&q=name%3D"+url.QueryEscape(short), nil, &list); err != nil {
		return 0, "", err
	}
	for _, r := range list {
		if r.Name == short || r.Name == "robot$"+short {
			return r.ID, r.Name, nil
		}
	}
	return 0, "", fmt.Errorf("harbor: robot %q not found", short)
}

// EnsureCluster provisions the cluster's private project and its push+pull robot.
//
// The robot is minted ONCE. A re-run returns the existing identity with an EMPTY secret, and the
// caller keeps the credential it already sealed - because this credential is delivered to the
// cluster as a Kubernetes pull Secret, and silently rotating it on a level-triggered re-run would
// leave every pod in the cluster unable to pull until the next wiring pass. That is the opposite of
// the mirror robot's trade, where the value reaches nodes on the next playbook run anyway.
func (c *Client) EnsureCluster(ctx context.Context, cl *domain.Cluster) (registry.RobotCredential, error) {
	project := c.set.ClusterProject(cl)
	if err := c.ensureProject(ctx, project, false, c.set.ProjectQuotaGB, ""); err != nil {
		return registry.RobotCredential{}, err
	}
	short := registry.ClusterRobot(cl)
	body := map[string]any{
		"name":        short,
		"description": fmt.Sprintf("KubeHarbor: push/pull credential for cluster %q", cl.Name),
		"duration":    int(c.set.RobotTTL.Hours() / 24),
		"level":       "system",
		"permissions": []map[string]any{{
			"kind":      "project",
			"namespace": project,
			"access": []map[string]string{
				{"resource": "repository", "action": "pull"},
				{"resource": "repository", "action": "push"},
				{"resource": "artifact", "action": "read"},
				{"resource": "tag", "action": "list"},
			},
		}},
	}
	var created struct {
		Name   string `json:"name"`
		Secret string `json:"secret"`
	}
	err := c.do(ctx, http.MethodPost, "/robots", body, &created)
	if err == nil && created.Secret != "" {
		c.emit(cl.ID, "info", fmt.Sprintf("provisioned registry project %q and its push/pull robot", project))
		return registry.RobotCredential{Username: created.Name, Secret: created.Secret,
			Expires: time.Now().Add(c.set.RobotTTL)}, nil
	}
	if err != nil && !strings.Contains(err.Error(), "409") {
		return registry.RobotCredential{}, err
	}
	_, name, err := c.findRobot(ctx, short)
	if err != nil {
		return registry.RobotCredential{}, err
	}
	// Identity only, no secret: the caller keeps the one it sealed the first time.
	return registry.RobotCredential{Username: name}, nil
}

// ReleaseCluster removes the cluster's robot and project. Absence is success, so it is safe on every
// deleting tick and on a retry. RetainProject keeps the images and drops only the credential - the
// credential is scoped to a project nobody can reach any more, but it is still a live credential.
func (c *Client) ReleaseCluster(ctx context.Context, cl *domain.Cluster) error {
	if id, _, err := c.findRobot(ctx, registry.ClusterRobot(cl)); err == nil {
		if err := c.do(ctx, http.MethodDelete, "/robots/"+strconv.FormatInt(id, 10), nil, nil,
			http.StatusNotFound); err != nil {
			return err
		}
	}
	if c.set.RetainProject {
		c.emit(cl.ID, "info", fmt.Sprintf("retained registry project %q (KAAS_REGISTRY_RETAIN_PROJECT)", c.set.ClusterProject(cl)))
		return nil
	}
	project := c.set.ClusterProject(cl)
	// Harbor refuses to delete a project that still holds repositories, so drop those first. A
	// project the platform created for a cluster holds only that cluster's images.
	repos, err := c.repositories(ctx, project)
	if err == nil {
		for _, r := range repos {
			_ = c.do(ctx, http.MethodDelete,
				"/projects/"+url.PathEscape(project)+"/repositories/"+repoPath(r.Name), nil, nil,
				http.StatusNotFound)
		}
	}
	if err := c.do(ctx, http.MethodDelete, "/projects/"+url.PathEscape(project), nil, nil,
		http.StatusNotFound, http.StatusBadRequest); err != nil {
		return err
	}
	// The cluster row still exists here: releaseRegistry runs in PhaseDeleting, BEFORE DestroyCluster
	// and before the row is dropped - so the event's FK holds.
	c.emit(cl.ID, "info", fmt.Sprintf("released registry project %q", project))
	return nil
}

// SyncAccess converges accounts and project memberships to registry.DesiredAccess(snap).
//
// It is additive plus corrective on the rows the platform owns: every desired membership is applied
// at its role, and a membership on a platform-owned project that the platform did not intend is
// removed. It deliberately does NOT touch projects it does not own (KindExternal), so a Harbor
// already used for other work keeps its own memberships.
func (c *Client) SyncAccess(ctx context.Context, snap registry.AccessSnapshot) error {
	desired := registry.DesiredAccess(snap, c.set)

	if c.set.AuthMode == registry.AuthLocal {
		for _, u := range desired.Users {
			if err := c.ensureLocalUser(ctx, u); err != nil {
				return err
			}
		}
	}
	for _, u := range desired.Users {
		if err := c.ensureSysAdmin(ctx, u); err != nil {
			// A user who has never logged in does not exist in ldap mode, which is ordinary rather
			// than exceptional - the flag lands on their next sweep after their first login.
			c.log.Debug("registry: could not set system-admin flag", "user", u.Username, "err", err)
		}
	}

	// Group the desired memberships by project so each project is read once.
	byProject := map[string][]registry.DesiredMember{}
	for _, m := range desired.Members {
		byProject[m.Project] = append(byProject[m.Project], m)
	}
	for project, want := range byProject {
		if err := c.syncProjectMembers(ctx, project, want); err != nil {
			return err
		}
	}
	return nil
}

// syncProjectMembers converges one project's membership list.
func (c *Client) syncProjectMembers(ctx context.Context, project string, want []registry.DesiredMember) error {
	type memberRow struct {
		ID     int64  `json:"id"`
		Name   string `json:"entity_name"`
		RoleID int    `json:"role_id"`
		Type   string `json:"entity_type"`
	}
	var have []memberRow
	if err := c.do(ctx, http.MethodGet,
		"/projects/"+url.PathEscape(project)+"/members?page_size=100", nil, &have,
		http.StatusNotFound); err != nil {
		return err
	}
	haveByName := map[string]memberRow{}
	for _, m := range have {
		haveByName[strings.ToLower(m.Name)] = m
	}
	wantByName := map[string]registry.DesiredMember{}
	for _, m := range want {
		wantByName[m.Username] = m
	}

	for _, m := range want {
		roleID := roleID(m.Role)
		existing, ok := haveByName[m.Username]
		switch {
		case !ok:
			body := map[string]any{
				"role_id":     roleID,
				"member_user": map[string]string{"username": m.Username},
			}
			if err := c.do(ctx, http.MethodPost,
				"/projects/"+url.PathEscape(project)+"/members", body, nil,
				http.StatusConflict, http.StatusNotFound, http.StatusBadRequest); err != nil {
				return err
			}
		case existing.RoleID != roleID:
			if err := c.do(ctx, http.MethodPut,
				"/projects/"+url.PathEscape(project)+"/members/"+strconv.FormatInt(existing.ID, 10),
				map[string]any{"role_id": roleID}, nil, http.StatusNotFound); err != nil {
				return err
			}
		}
	}
	// Remove memberships the platform no longer intends - a user removed from a group must lose
	// their pull access, or the "access convergence" claim is only half true. The project owner
	// (Harbor's own admin account) is never a row here, so there is nothing to protect from this.
	for name, m := range haveByName {
		if _, ok := wantByName[name]; ok {
			continue
		}
		if m.Type != "u" {
			continue // a group membership someone added by hand: not ours to remove
		}
		if err := c.do(ctx, http.MethodDelete,
			"/projects/"+url.PathEscape(project)+"/members/"+strconv.FormatInt(m.ID, 10), nil, nil,
			http.StatusNotFound); err != nil {
			return err
		}
	}
	return nil
}

// ensureLocalUser creates the platform's account in Harbor's own user database (local auth mode
// only). The password is a throwaway: the account cannot be used until its owner generates one from
// the portal, which is the whole local-mode credential story.
func (c *Client) ensureLocalUser(ctx context.Context, u registry.DesiredUser) error {
	body := map[string]any{
		"username": u.Username,
		"email":    u.Email,
		"realname": u.Realname,
		"password": randomPassword(),
		"comment":  "Managed by KubeHarbor",
	}
	return c.do(ctx, http.MethodPost, "/users", body, nil, http.StatusConflict, http.StatusForbidden)
}

// ensureSysAdmin makes platform admins registry system admins (and demotes anyone who stopped being
// one), so an admin sees every project without a membership row per cluster.
func (c *Client) ensureSysAdmin(ctx context.Context, u registry.DesiredUser) error {
	id, current, err := c.findUser(ctx, u.Username)
	if err != nil {
		return err
	}
	if current == u.SysAdmin {
		return nil
	}
	return c.do(ctx, http.MethodPut, "/users/"+strconv.FormatInt(id, 10)+"/sysadmin",
		map[string]any{"sysadmin_flag": u.SysAdmin}, nil)
}

func (c *Client) findUser(ctx context.Context, username string) (int64, bool, error) {
	var list []struct {
		ID       int64  `json:"user_id"`
		Username string `json:"username"`
		Admin    bool   `json:"sysadmin_flag"`
	}
	if err := c.do(ctx, http.MethodGet, "/users/search?username="+url.QueryEscape(username), nil, &list); err != nil {
		return 0, false, err
	}
	for _, u := range list {
		if strings.EqualFold(u.Username, username) {
			// The search endpoint omits the admin flag, so read the user back for it.
			var full struct {
				Admin bool `json:"sysadmin_flag"`
			}
			if err := c.do(ctx, http.MethodGet, "/users/"+strconv.FormatInt(u.ID, 10), nil, &full); err != nil {
				return u.ID, u.Admin, nil
			}
			return u.ID, full.Admin, nil
		}
	}
	return 0, false, fmt.Errorf("harbor: user %q not found", username)
}

// SetUserPassword sets one local account's password. Admin-driven, so it needs no old password -
// and the platform never learns or stores the value it just applied beyond the one response that
// carries it back to its owner.
func (c *Client) SetUserPassword(ctx context.Context, username, password string) error {
	id, _, err := c.findUser(ctx, username)
	if err != nil {
		return err
	}
	return c.do(ctx, http.MethodPut, "/users/"+strconv.FormatInt(id, 10)+"/password",
		map[string]any{"new_password": password}, nil)
}

