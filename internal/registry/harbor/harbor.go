// Config builds a Client.
type Config struct {
	Settings registry.Settings
	Events   events.Sink
	Log      *slog.Logger
}

// Client is the real registry seam.
type Client struct {
	base string
	set  registry.Settings
	user string
	pass string
	http *http.Client
	ev   events.Sink
	log  *slog.Logger

	// mu guards the cached status, which is read on every Registry page load and would otherwise put
	// a health round-trip on the critical path of every request.
	mu       sync.Mutex
	status   registry.Status
	statusAt time.Time
}

// statusTTL bounds how stale the cached health may be. A registry that has just come back should
// stop being reported as down promptly, but not at the cost of a round-trip per page load.
const statusTTL = 20 * time.Second

// New builds a Client from validated settings.
func New(cfg Config) (*Client, error) {
	s, err := cfg.Settings.Validate()
	if err != nil {
		return nil, err
	}
	if !s.Enabled() {
		return nil, fmt.Errorf("harbor: KAAS_REGISTRY_URL is required")
	}
	tr := &http.Transport{}
	if s.Insecure {
		tr.TLSClientConfig = &tls.Config{InsecureSkipVerify: true}
	}
	return &Client{
		base: strings.TrimRight(s.URL, "/") + "/api/v2.0",
		set:  s,
		user: s.Username,
		pass: s.Password,
		http: &http.Client{Timeout: 30 * time.Second, Transport: tr},
		ev:   cfg.Events,
		log:  cfg.Log,
	}, nil
}

// do performs one Harbor API call. okCodes are statuses treated as success besides 2xx - Harbor
// answers "already exists" with 409 on nearly every create, which is exactly what an idempotent
// upsert wants to ignore.
func (c *Client) do(ctx context.Context, method, path string, body, out any, okCodes ...int) error {
	var rdr io.Reader
	if body != nil {
		b, err := json.Marshal(body)
		if err != nil {
			return err
		}
		rdr = bytes.NewReader(b)
	}
	req, err := http.NewRequestWithContext(ctx, method, c.base+path, rdr)
	if err != nil {
		return err
	}
	req.SetBasicAuth(c.user, c.pass)
	req.Header.Set("Accept", "application/json")
	if body != nil {
		req.Header.Set("Content-Type", "application/json")
	}
	resp, err := c.http.Do(req)
	if err != nil {
		return fmt.Errorf("harbor: %s %s: %w", method, path, err)
	}
	defer resp.Body.Close()
	data, _ := io.ReadAll(io.LimitReader(resp.Body, 4<<20))
	if resp.StatusCode >= 200 && resp.StatusCode < 300 {
		if out != nil && len(data) > 0 {
			return json.Unmarshal(data, out)
		}
		return nil
	}
	for _, ok := range okCodes {
		if resp.StatusCode == ok {
			return nil
		}
	}
	return fmt.Errorf("harbor: %s %s: %d: %s", method, path, resp.StatusCode, strings.TrimSpace(string(data)))
}

// emit puts a message on a CLUSTER's activity timeline, or logs it when the message is
// platform-scoped. The split is forced by the schema exactly as it is in hcvault: events.cluster_id
// is NOT NULL and foreign-keyed, so an emit with no cluster id is a guaranteed FK violation that
// surfaces as a database error rather than a dropped log line.
func (c *Client) emit(clusterID, level, msg string) {
	if clusterID == "" {
		if c.log != nil {
			if level == "warn" {
				c.log.Warn(msg)
			} else {
				c.log.Info(msg)
			}
		}
		return
	}
	if c.ev != nil {
		c.ev.Emit(events.Event{ClusterID: clusterID, Source: "registry", Level: level, Message: msg})
	}
}

