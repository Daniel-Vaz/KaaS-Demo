// Package harbor is the real registry.Manager + registry.Querier: a thin net/http client against
// Harbor's /api/v2.0 REST API (the same shape as internal/netbox and internal/vault/hcvault). It is
// built only where a credential lives - the WORKER (the admin credential, driving
// EnsurePlatform/EnsureCluster/ReleaseCluster/SyncAccess) and the API (a read-only robot, calling
// only the Querier half). Every write is an idempotent upsert, so it is safe to re-run on every
// reconcile tick and every SyncAccess sweep.
//
// Shortcuts, in the repo's style (documented rather than hidden):
//   - The API is given a read-only system robot through the environment rather than one minted and
//     handed over by the worker. Production would provision it out of band (or federate both
//     processes behind an IdP) so no long-lived credential sits in two env files.
//   - Local-mode user passwords are generated by the platform, applied here, and shown to their owner
//     once. Production would run OIDC in front of both the portal and Harbor so no password is
//     generated, copied or displayed at all.
//   - A robot is minted with a long TTL and never rotated. The expiry is recorded on the cluster row
//     (Cluster.RegistryRobotNotAfter) so a rotation sweep can be added as a time-driven due-scan,
//     exactly like certificate renewal.
